"""
Split Node for tensor splitting with configurable slicing
Splits a single tensor input into up to 4 outputs based on indices or sizes
"""

from inspect import cleandoc
from custom_nodes.utils.visnode_base import RoboticsNodeBase
from custom_nodes.utils.node_colors import get_node_colors
from custom_nodes.utils.dnne_decorator import dnne_node

@dnne_node(is_virtual=False)
class SplitNode(RoboticsNodeBase):
    """
    Split Node for tensor splitting
    Splits a single tensor input into up to 4 outputs along a specified dimension
    
    Modes:
    - by index: Extract specific index ranges or split at indices
        • Ranges (inclusive): "[3:5], [10:18]" extracts indices 3-5 and 10-18
        • Single indices: "3, 7, 9" extracts individual indices
        • Split points: "10,20,30" splits at positions creating [0:10], [10:20], [20:30], [30:]
    - by size: Split into chunks of specific sizes (e.g., "10,10,10,10" creates 4 chunks of size 10)
    - by name: Split using semantic names from upstream schema (e.g., "joint_positions,joint_velocities")
    
    The number of outputs depends on the split_pos specification:
    - For "by index" with ranges: One output per range specified
    - For "by index" with split points: Creates N+1 outputs for N indices
    - For "by size" with N non-zero sizes: Creates N outputs
    - For "by name" with N names: Creates N outputs
    """
    
    CATEGORY = "utility"
    COLOR = get_node_colors("utility")["color"]
    BGCOLOR = get_node_colors("utility")["bgcolor"]
    
    @classmethod
    def INPUT_TYPES(cls):
        return {
            "required": {
                "input": ("*TENSOR", {"tooltip": "Input tensor to split"}),
                "dimension": ("INT", {
                    "default": 0,
                    "min": 0,
                    "max": 3,
                    "tooltip": "Dimension along which to split the tensor (0=batch, 1=channels, etc.)"
                }),
                "split_mode": (["by index", "by size", "by name"], {
                    "default": "by index",
                    "tooltip": "How to interpret split_pos: indices, sizes, or semantic names from schema"
                }),
                "split_pos": ("STRING", {
                    "default": "10,20,30",
                    "tooltip": "Comma-separated values. 'by index': ranges like [3:5],[10:18] (inclusive) or split points. 'by size': chunk sizes. 'by name': semantic names from schema."
                }),
            }
        }

    OUTPUT_DICT = {
        0: {"type": "*TENSOR", "name": "output_a"},
        1: {"type": "*TENSOR", "name": "output_b"},
        2: {"type": "*TENSOR", "name": "output_c"},
        3: {"type": "*TENSOR", "name": "output_d"}
    }
    # RETURN_TYPES and RETURN_NAMES auto-generated by OutputDictMixin
    FUNCTION = None  # DNNE nodes don't execute in UI, only export
    DESCRIPTION = cleandoc(__doc__)

# Node registration
NODE_CLASS_MAPPINGS = {
    "Split": SplitNode
}

NODE_DISPLAY_NAME_MAPPINGS = {
    "Split": "Split"
}